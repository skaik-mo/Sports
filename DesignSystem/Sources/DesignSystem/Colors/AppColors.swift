import SwiftUI

public enum AppColors { 

    // MARK: - Primary
    public static let primary = Color("primary", bundle: .module)

    // MARK: - Background
    public static let background = Color("background", bundle: .module)
    public static let secondaryBackground = Color("secondaryBackground", bundle: .module)

    // MARK: - Foreground
    public static let foreground = Color("foreground", bundle: .module)

    // MARK: - Text
    public static let primaryText = Color("primaryText", bundle: .module)
    public static let secondaryText = Color("secondaryText", bundle: .module)

    // MARK: - Shadow
    public static let shadow = Color("shadow", bundle: .module)

    // MARK: - Stroke
    public static let stroke = Color("stroke", bundle: .module)

    // MARK: Others
    public static let white = Color("white", bundle: .module)
    public static let clear = Color("clear", bundle: .module)
}
